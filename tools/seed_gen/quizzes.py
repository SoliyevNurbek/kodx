def S(text, correct, *wrong, explanation=""):
    """Bitta to'g'ri javobli savol (variantlar deterministik aralashtiriladi)."""
    options = [(correct, True)] + [(w, False) for w in wrong]
    random.Random(text).shuffle(options)
    return {"text": text, "kind": "single", "options": options, "explanation": explanation}


def M(text, correct, wrong, explanation=""):
    """Bir nechta to'g'ri javobli savol."""
    options = [(c, True) for c in correct] + [(w, False) for w in wrong]
    random.Random(text).shuffle(options)
    return {"text": text, "kind": "multiple", "options": options, "explanation": explanation}


def T(text, *answers, explanation=""):
    """Qisqa matnli javob (katta-kichik harf farqlanmaydi)."""
    return {"text": text, "kind": "text", "answers": list(answers), "explanation": explanation}


